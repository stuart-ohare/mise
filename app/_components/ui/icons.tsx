import type { ReactNode } from "react";

/**
 * The handful of icons the app uses, inline rather than a package (CLAUDE.md §4.5). All
 * decorative: every one sits beside text that already says the same thing, so a safety
 * cue never depends on seeing the icon or its colour.
 */

type IconProps = { className?: string };

function Svg({ className = "size-4", children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      aria-hidden
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className}`}
    >
      {children}
    </svg>
  );
}

